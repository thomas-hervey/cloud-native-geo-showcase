import summaryJson from '@/content/spatial-eval/run-summary.json';
import { buildRunComparison, runSummarySchema } from '@/lib/spatial-eval-runs';
import { RunComparisonSection } from './_components/RunComparisonSection';
import { StreamlitPanel } from './_components/StreamlitPanel';
import { StoryFindings } from './_components/StoryFindings';
import { EvalLadder } from './_components/EvalLadder';
import storyJson from '@/content/spatial-eval/story-findings.json';
import { storyFindingsSchema } from '@/lib/spatial-eval-story';

/**
 * Spatial Eval — "Where do LLMs think neighborhoods are?"
 *
 * Story findings are generated by
 *   cd src/exercises/spatial-eval && uv run --with duckdb --with shapely --with pyproj python scripts/export_story_findings.py
 * Run-comparison data is generated by
 *   cd src/exercises/spatial-eval && uv run python scripts/export_run_summary.py --db duckdb
 */
const summary = runSummarySchema.parse(summaryJson);
const comparison = buildRunComparison(summary);
const story = storyFindingsSchema.parse(storyJson);

export default function SpatialEvalPage() {
  return (
    <div className="bg-gray-50 pb-12">
      <StreamlitPanel />
      <div className="space-y-6 px-4 sm:px-8">
        <StoryFindings findings={story} />
        {comparison && (
          <RunComparisonSection
            comparison={comparison}
            referenceSource={summary.referenceSource}
            placeCount={summary.placeCount}
          />
        )}
        <EvalLadder />
      </div>
    </div>
  );
}
