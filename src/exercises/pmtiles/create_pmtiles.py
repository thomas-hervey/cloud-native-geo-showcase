# Title: Create PMTiles Archive
# Description: Uses the pmtiles library to package vector data into a serverless archive.

import os
import json
from pathlib import Path
from pmtiles.writer import Writer
from pmtiles.reader import Reader, MemorySource
import gzip

def create_mock_vector_tile(layer_name, feature_id, lon, lat):
    """
    Creates a simple mock vector tile (MVT) structure.
    In a real scenario, this would be generated by a library like `tippecanoe` 
    or `mapbox-vector-tile`. Here we simulate the binary payload.
    """
    # This is a very simplified mock of a vector tile payload
    mock_payload = f"MVT_LAYER:{layer_name}_ID:{feature_id}_COORD:{lon},{lat}".encode()
    return gzip.compress(mock_payload)

def main():
    root_path = Path(__file__).parent
    output_path = root_path / "data" / "demo.pmtiles"
    output_path.parent.mkdir(exist_ok=True)

    print("Initializing PMTiles Writer...")
    # PMTiles V3 requires a file or stream to write to
    with open(output_path, "wb") as f:
        writer = Writer(f)
        
        # 1. Define Metadata
        metadata = {
            "name": "PMTiles Demo",
            "description": "Serverless vector tile demo for Module 19",
            "attribution": "Cloud-Native Geo Tutorial",
            "vector_layers": [
                {
                    "id": "points",
                    "fields": {"id": "number"}
                }
            ]
        }
        
        # 2. Start Writing Tiles
        # PMTiles organizes tiles by Z/X/Y
        # Let's add a few mock tiles at Zoom 0 and Zoom 1
        print("Writing mock tiles to archive...")
        
        # Zoom 0, X 0, Y 0 (The whole world)
        tile_z0 = create_mock_vector_tile("points", "global", 0, 0)
        writer.write_tile(pmtiles.tile.zxy_to_tileid(0, 0, 0), tile_z0)
        
        # Zoom 1, arbitrary tiles
        writer.write_tile(pmtiles.tile.zxy_to_tileid(1, 0, 0), create_mock_vector_tile("points", "NW", -90, 45))
        writer.write_tile(pmtiles.tile.zxy_to_tileid(1, 1, 0), create_mock_vector_tile("points", "NE", 90, 45))
        writer.write_tile(pmtiles.tile.zxy_to_tileid(1, 0, 1), create_mock_vector_tile("points", "SW", -90, -45))
        writer.write_tile(pmtiles.tile.zxy_to_tileid(1, 1, 1), create_mock_vector_tile("points", "SE", 90, -45))
        
        # 3. Finalize
        print("Finalizing archive...")
        writer.finalize({
            "tile_type": pmtiles.tile.TileType.MVT,
            "tile_compression": pmtiles.tile.Compression.GZIP,
            "min_zoom": 0,
            "max_zoom": 1,
            "min_lon": -180,
            "min_lat": -85,
            "max_lon": 180,
            "max_lat": 85
        }, json.dumps(metadata))

    print(f"\n✅ SUCCESS: Archive created at {output_path}")
    print(f"File Size: {output_path.stat().st_size} bytes")

    # 4. Verify with Reader
    print("\nVerifying archive with Reader...")
    with open(output_path, "rb") as f:
        reader = Reader(MemorySource(f.read()))
        header = reader.header()
        print(f"  Header Type: {header['tile_type']}")
        print(f"  Zoom Range: {header['min_zoom']} - {header['max_zoom']}")
        
        # Try to read a specific tile index
        tile_data = reader.get(1, 1, 0)
        if tile_data:
            print(f"  Tile (1,1,0) Read Success! Size: {len(tile_data)} bytes")

# Simple hack to get pmtiles enums if not imported cleanly in this environment
import pmtiles
if __name__ == "__main__":
    main()
