"""
Exercise 1: Embed the STAC Catalog into ChromaDB
===================================================================

Reads the STAC catalog generated by the STAC Cataloging exercise and builds a local
ChromaDB vector index using sentence-transformers (no API key, no cost).

Architecture:
  - Python owns the embedding pipeline (this script)
  - ChromaDB stores the vectors persistently on disk
  - Exercise 03 will export a flat JSON snapshot for the Next.js API route
  - Next.js does cosine similarity at query time against the JSON snapshot

Each STAC dataset item is broken into multiple "chunks" before embedding,
so the retrieval is fine-grained by chunk type:
  - title_description: what the dataset is
  - schema_fields: column names and types
  - category_vocabulary: valid values (for places-type datasets)

Idempotent: upsert semantics — safe to re-run after re-generating the catalog.

Run:
    cd src/exercises/
    uv run python vector-rag/01_embed_catalog.py

Requires:
    The STAC Cataloging exercise must have been run first (output/stac/ must exist).

Output:
    vector-rag/output/chroma/   (persistent ChromaDB store)
"""

import json
from pathlib import Path

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

STAC_DIR = (
    Path(__file__).parent.parent
    / "scout-etl"
    / "output"
    / "stac"
)

# We use pystac just to load — no need to install again, already in pyproject.toml
STAC_ITEM_PATH = (
    STAC_DIR / "sf-places" / "sf-places-2026" / "sf-places-2026.json"
)

CHROMA_DIR = Path(__file__).parent / "output" / "chroma"

# Local embedding model — runs entirely offline, no API key required.
# ~80MB download on first run, then cached by HuggingFace.
EMBEDDING_MODEL = "all-MiniLM-L6-v2"

# ChromaDB collection name — all Scout schema chunks go here
COLLECTION_NAME = "scout_schema_chunks"


# ---------------------------------------------------------------------------
# Chunk builders
# ---------------------------------------------------------------------------

def build_chunks_from_stac_item(item_path: Path) -> list[dict]:
    """
    Turn a STAC item into a list of text chunks suitable for embedding.

    Each chunk is a dict with:
      - id:       unique string ID within the collection
      - text:     the text to be embedded
      - metadata: dict of arbitrary key/value pairs (stored alongside the vector)
    """
    with open(item_path) as f:
        item = json.load(f)

    props = item["properties"]
    dataset_id = item["id"]
    bbox = item.get("bbox", [])

    chunks = []

    # -- Chunk 1: Title + description (what the dataset is about) ------------
    title = props.get("title", dataset_id)
    description = props.get("description", "")
    chunks.append({
        "id": f"{dataset_id}:title_description",
        "text": f"{title}. {description}",
        "metadata": {
            "dataset_id": dataset_id,
            "chunk_type": "title_description",
            "bbox_xmin": bbox[0] if len(bbox) >= 4 else None,
            "bbox_ymin": bbox[1] if len(bbox) >= 4 else None,
            "bbox_xmax": bbox[2] if len(bbox) >= 4 else None,
            "bbox_ymax": bbox[3] if len(bbox) >= 4 else None,
        },
    })

    # -- Chunk 2: Schema fields (column names + descriptions) ----------------
    schema: dict[str, str] = props.get("scout:schema", {})
    table_name: str = props.get("scout:table_name", dataset_id)
    duckdb_notes: str = props.get("scout:duckdb_notes", "")
    row_count: int = props.get("scout:row_count", 0)

    schema_lines = [f"Table: {table_name} ({row_count:,} rows)"]
    for col, desc in schema.items():
        schema_lines.append(f"  {col}: {desc}")
    schema_lines.append(f"DuckDB notes: {duckdb_notes}")

    chunks.append({
        "id": f"{dataset_id}:schema_fields",
        "text": "\n".join(schema_lines),
        "metadata": {
            "dataset_id": dataset_id,
            "chunk_type": "schema_fields",
            "table_name": table_name,
            "row_count": row_count,
            "duckdb_notes": duckdb_notes,
            # Store full schema as JSON string for retrieval
            "schema_json": json.dumps(schema),
        },
    })

    # -- Chunk 3: Category vocabulary (if present) ---------------------------
    categories: list[str] = props.get("scout:categories", [])
    if categories:
        # Embed all categories as a single natural-language block
        cat_text = (
            f"Valid category values for {table_name}: "
            + ", ".join(categories)
        )
        chunks.append({
            "id": f"{dataset_id}:category_vocabulary",
            "text": cat_text,
            "metadata": {
                "dataset_id": dataset_id,
                "chunk_type": "category_vocabulary",
                "table_name": table_name,
                "categories_json": json.dumps(categories),
            },
        })

    return chunks


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    print("=" * 60)
    print("Exercise 1: Build Vector Index")
    print("=" * 60)

    # Validate inputs
    if not STAC_ITEM_PATH.exists():
        print(f"\n  ERROR: STAC item not found at {STAC_ITEM_PATH}")
        print("  Run src/exercises/scout-etl/03_build_stac_catalog.py first.\n")
        raise SystemExit(1)

    # Lazy imports (heavy) — only after validation
    import chromadb
    from chromadb.utils import embedding_functions

    CHROMA_DIR.mkdir(parents=True, exist_ok=True)

    # -- Setup ChromaDB with sentence-transformers embedding function ---------
    print(f"\n  Embedding model  : {EMBEDDING_MODEL}")
    print(f"  Chroma store     : {CHROMA_DIR}")
    print(f"  Collection       : {COLLECTION_NAME}")
    print()
    print("  (First run downloads ~80MB model from HuggingFace — cached after.)")
    print()

    client = chromadb.PersistentClient(path=str(CHROMA_DIR))
    ef = embedding_functions.SentenceTransformerEmbeddingFunction(
        model_name=EMBEDDING_MODEL
    )

    # get_or_create so this is idempotent
    collection = client.get_or_create_collection(
        name=COLLECTION_NAME,
        embedding_function=ef,
        metadata={"hnsw:space": "cosine"},
    )

    # -- Build chunks from STAC items ----------------------------------------
    print("1/3  Building chunks from STAC catalog...")
    chunks = build_chunks_from_stac_item(STAC_ITEM_PATH)
    print(f"     {len(chunks)} chunks from sf-places-2026")
    print()

    # -- Upsert into ChromaDB ------------------------------------------------
    print("2/3  Upserting into ChromaDB (embedding on first run)...")
    collection.upsert(
        ids=[c["id"] for c in chunks],
        documents=[c["text"] for c in chunks],
        metadatas=[c["metadata"] for c in chunks],
    )
    count = collection.count()
    print(f"     Collection now contains {count} documents")
    print()

    # -- Smoke test: query the index ------------------------------------------
    print("3/3  Smoke test: querying 'coffee shops near a park'...")
    results = collection.query(
        query_texts=["coffee shops near a park"],
        n_results=3,
    )
    for i, (doc, meta, dist) in enumerate(zip(
        results["documents"][0],
        results["metadatas"][0],
        results["distances"][0],
    )):
        similarity = 1 - dist  # ChromaDB cosine distance: 0=identical, 2=opposite
        chunk_type = meta.get("chunk_type", "?")
        dataset = meta.get("dataset_id", "?")
        print(f"     [{i+1}] {dataset}:{chunk_type}  sim={similarity:.3f}")
        print(f"          {doc[:100]}...")

    print()
    print("=" * 60)
    print("Vector index built successfully.")
    print(f"Next: Run 02_retrieval_compare.py to see the token delta.")
    print("=" * 60)


if __name__ == "__main__":
    main()
